use chrono::{DateTime, Utc};
use serde::{Deserialize, Serialize};

use crate::catalogue::Capability;
use crate::params::{Answer, Flag, Strategy};

/// What a flow intends for one event, and the path that led there. Nothing in it has run.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct Plan {
    /// The flow ran: the trigger matched the event and its liveness rule held.
    pub ran: bool,
    /// Why it did not run.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub ignored: Option<Ignored>,
    /// Every node visited, in order, with what happened there.
    #[serde(default)]
    pub path: Vec<Step>,
    /// The intended actions in path order; [`Outcome::Planned`] points into it.
    #[serde(default)]
    pub actions: Vec<PlannedAction>,
    /// A `stop` node was reached: the flows after this one do not run for the event.
    #[serde(default)]
    pub stopped: bool,
}

/// Why a flow did not run for an event.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Ignored {
    /// The event is of another kind than the flow's trigger.
    OtherTrigger,
    /// The message is not live mail (backfill, import, resync or rebuild).
    NotLive,
}

/// One node visited.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Step {
    /// Node id.
    pub node: String,
    /// Node type id.
    #[serde(rename = "type")]
    pub kind: String,
    /// What happened.
    #[serde(flatten)]
    pub outcome: Outcome,
}

/// What happened at a node.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(tag = "outcome", rename_all = "snake_case")]
pub enum Outcome {
    /// A condition took this port.
    Branch {
        /// `yes` or `no`.
        port: String,
    },
    /// An action was planned.
    Planned {
        /// Index into [`Plan::actions`].
        action: usize,
    },
    /// An action was left out; the run goes on through `next`.
    Skipped {
        /// Why.
        reason: Skip,
    },
    /// A `stop` node.
    Stopped,
}

/// Why an action was left out.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(tag = "code", rename_all = "snake_case")]
pub enum Skip {
    /// The event has no message.
    NoMessage,
    /// The message has no sender address.
    NoSender,
    /// The event has no invitation.
    NoInvitation,
    /// `Auto-Submitted` other than `no`, or `X-Auto-Response-Suppress` (RFC 3834).
    AutoSubmitted,
    /// `List-Id`, `List-Post` or `List-Unsubscribe` (RFC 3834).
    MailingList,
    /// `Precedence: bulk`, `list` or `junk`.
    BulkPrecedence,
    /// An empty `Return-Path` (RFC 3834).
    NullReturnPath,
    /// The sender is a no-reply, daemon, bounce or list-robot address.
    NoReplySender,
    /// The sender is one of the archive's own addresses, so it could loop.
    OwnAddress,
    /// This flow replied to the sender less than its days ago.
    RepliedRecently {
        /// When the next reply may go.
        until: DateTime<Utc>,
    },
    /// The sender is already a person in People.
    AlreadyKnown,
    /// A template failed.
    Template {
        /// The parameter.
        field: String,
        /// The error, about the template only.
        error: String,
    },
    /// `starts` did not render to an RFC 3339 time.
    BadDate,
}

/// An action the server may carry out.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct PlannedAction {
    /// The node that planned it.
    pub node: String,
    /// The account capability it needs; `None` for local actions.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub capability: Option<Capability>,
    /// It waits for a person (a draft or a pending entry) instead of running.
    #[serde(default)]
    pub needs_confirmation: bool,
    /// What to do.
    pub action: Action,
}

/// The `Auto-Submitted` value (RFC 3834) a message sent by a rule carries.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum AutoSubmitted {
    /// A reply to a message.
    #[serde(rename = "auto-replied")]
    AutoReplied,
    /// Anything else a rule sends.
    #[serde(rename = "auto-generated")]
    AutoGenerated,
}

/// What to do. Text fields are rendered templates.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(tag = "type", rename_all = "snake_case")]
#[allow(missing_docs)]
pub enum Action {
    /// A local label on the message.
    Label { message: String, name: String },
    /// Flags on the server.
    SetFlags {
        message: String,
        set: Vec<Flag>,
        clear: Vec<Flag>,
    },
    /// Move on the server.
    Move { message: String, folder: String },
    /// Move to Trash on the server.
    Delete { message: String },
    /// An automatic reply to `to` only, the sender the RFC 3834 checks ran on, never the
    /// message's `Reply-To`; once queued, the server records it as this flow's last reply to that
    /// sender.
    Reply {
        message: String,
        identity: String,
        to: String,
        subject: String,
        body: String,
        days: u32,
        auto_submitted: AutoSubmitted,
    },
    /// Forward the message.
    Forward {
        message: String,
        identity: String,
        to: Vec<String>,
        #[serde(default, skip_serializing_if = "Option::is_none")]
        note: Option<String>,
        as_attachment: bool,
        auto_submitted: AutoSubmitted,
    },
    /// A new message.
    Send {
        identity: String,
        to: Vec<String>,
        subject: String,
        body: String,
        auto_submitted: AutoSubmitted,
    },
    /// Answer the invitation with this `UID`.
    Rsvp {
        #[serde(default, skip_serializing_if = "Option::is_none")]
        message: Option<String>,
        uid: String,
        answer: Answer,
        #[serde(default, skip_serializing_if = "Option::is_none")]
        comment: Option<String>,
    },
    /// A new event.
    CreateEvent {
        #[serde(default, skip_serializing_if = "Option::is_none")]
        calendar: Option<String>,
        title: String,
        starts: DateTime<Utc>,
        duration_minutes: u32,
    },
    /// The sender as a new contact.
    CreateContact {
        #[serde(default, skip_serializing_if = "Option::is_none")]
        address_book: Option<String>,
        #[serde(default, skip_serializing_if = "Option::is_none")]
        name: Option<String>,
        address: String,
    },
    /// A notification on the owner's devices.
    Notify { title: String, body: String },
    /// Call a webhook with the event.
    Webhook { hook: String },
    /// Send the outgoing message as this identity.
    SetIdentity { identity: String },
    /// Send it through this transport.
    SetTransport { transport: String },
    /// Route it with this alias strategy.
    SetAliasStrategy { strategy: Strategy },
    /// Add a blind copy.
    AddBcc { address: String },
    /// Hold it until the sender confirms.
    RequireConfirmation { reason: String },
    /// Refuse to send it.
    Block { reason: String },
}
