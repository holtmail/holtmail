//! Which instance of a repeating event a `RECURRENCE-ID` names: the same instant however it is
//! written (`...Z`, a `TZID`, a floating time), and whether the series has it at all.

use chrono::{NaiveDate, NaiveDateTime};
use holtmail_pim::{ItemKind, Normalized};
use holtmail_recur::Window;

use crate::lines::{Component, Line, parameter};
use crate::model::Item;

const DAY_MS: i64 = 86_400_000;

/// Whether `value` reads as an iCalendar date or date-time.
pub(crate) fn well_formed(value: &str) -> bool {
    let v = value.strip_suffix('Z').unwrap_or(value);
    match v.len() {
        8 if !value.ends_with('Z') => NaiveDate::parse_from_str(v, "%Y%m%d").is_ok(),
        15 => NaiveDateTime::parse_from_str(v, "%Y%m%dT%H%M%S").is_ok(),
        _ => false,
    }
}

/// The parameters of a `RECURRENCE-ID` written like `series`' `DTSTART`.
pub(crate) fn series_params(series: &Component, value: &str) -> String {
    match series.line("DTSTART") {
        Some(s)
            if s.param("VALUE")
                .is_some_and(|v| v.eq_ignore_ascii_case("DATE")) =>
        {
            ";VALUE=DATE".to_owned()
        }
        Some(s) if !value.ends_with('Z') => s
            .param("TZID")
            .map(|tz| format!(";TZID={}", parameter(tz)))
            .unwrap_or_default(),
        _ => String::new(),
    }
}

fn key_of_written(item: &Item, params: &str, value: &str) -> Option<String> {
    let mut probe = item.clone();
    probe.top.children.retain(|c| c.name != "VEVENT");
    let lines: Vec<Line> = [
        "UID:probe".to_owned(),
        format!("RECURRENCE-ID{params}:{value}"),
        format!("DTSTART{params}:{value}"),
    ]
    .iter()
    .filter_map(|l| Line::parse(l))
    .collect();
    probe.top.children.push(Component {
        name: "VEVENT".into(),
        lines,
        children: Vec::new(),
    });
    let Normalized::Calendar(calendar) = holtmail_pim::normalize(ItemKind::Event, &probe.write())
    else {
        return None;
    };
    calendar.components.first()?.key()?.recurrence_id
}

fn line_params(line: &Line) -> String {
    let mut out = String::new();
    if let Some(tz) = line.param("TZID") {
        out.push_str(&format!(";TZID={}", parameter(tz)));
    }
    if line
        .param("VALUE")
        .is_some_and(|v| v.eq_ignore_ascii_case("DATE"))
    {
        out.push_str(";VALUE=DATE");
    }
    out
}

/// The instance a component's `RECURRENCE-ID` names; `None` for the series itself.
pub(crate) fn key_of(item: &Item, component: &Component) -> Option<String> {
    let line = component.line("RECURRENCE-ID")?;
    key_of_written(item, &line_params(line), line.value.trim())
}

/// The instance `value`, written as the series writes its start, names in `item`.
pub(crate) fn key_of_value(item: &Item, value: &str) -> Option<String> {
    if !well_formed(value) {
        return None;
    }
    let components = item.components();
    let shape = components
        .iter()
        .find(|c| c.line("RECURRENCE-ID").is_none())
        .or(components.first())?;
    key_of_written(item, &series_params(shape, value), value)
}

/// Where among `item`'s children the changed instance named `key` is.
pub(crate) fn position(item: &Item, key: &str) -> Option<usize> {
    item.top.children.iter().position(|c| {
        c.name == "VEVENT"
            && c.line("RECURRENCE-ID").is_some()
            && key_of(item, c).as_deref() == Some(key)
    })
}

/// Whether the series in `item` has an instance named `key`: generated by its rule or `RDATE`s,
/// not removed by an `EXDATE`.
pub(crate) fn occurs(item: &Item, key: &str) -> bool {
    let Some(day) = key
        .get(..10)
        .and_then(|d| NaiveDate::parse_from_str(d, "%Y-%m-%d").ok())
        .and_then(|d| d.and_hms_opt(0, 0, 0))
    else {
        return false;
    };
    let Normalized::Calendar(calendar) = holtmail_pim::normalize(ItemKind::Event, &item.write())
    else {
        return false;
    };
    let at = day.and_utc().timestamp_millis();
    let window = Window {
        from: at - 2 * DAY_MS,
        to: at + 3 * DAY_MS,
    };
    holtmail_recur::expand(&calendar, window)
        .occurrences
        .iter()
        .any(|o| o.recurrence_id.as_deref() == Some(key))
}

#[cfg(test)]
mod tests {
    use super::*;

    const ZONED: &str = "BEGIN:VCALENDAR\r\nVERSION:2.0\r\nBEGIN:VEVENT\r\nUID:a@example.com\r\nDTSTART;TZID=Europe/Berlin:20261201T100000\r\nDTEND;TZID=Europe/Berlin:20261201T103000\r\nRRULE:FREQ=WEEKLY;COUNT=4\r\nEXDATE;TZID=Europe/Berlin:20261215T100000\r\nEND:VEVENT\r\nBEGIN:VEVENT\r\nUID:a@example.com\r\nRECURRENCE-ID;TZID=Europe/Berlin:20261208T100000\r\nDTSTART;TZID=Europe/Berlin:20261208T120000\r\nEND:VEVENT\r\nEND:VCALENDAR\r\n";

    #[test]
    fn an_instance_is_found_by_its_instant() {
        let item = Item::parse(ItemKind::Event, ZONED.as_bytes()).unwrap();
        let local = key_of_value(&item, "20261208T100000").unwrap();
        let utc = key_of_value(&item, "20261208T090000Z").unwrap();
        assert_eq!(local, utc);
        assert!(position(&item, &utc).is_some());
        assert!(position(&item, &key_of_value(&item, "20261208T110000").unwrap()).is_none());
    }

    #[test]
    fn only_real_occurrences_count() {
        let item = Item::parse(ItemKind::Event, ZONED.as_bytes()).unwrap();
        let has = |v| occurs(&item, &key_of_value(&item, v).unwrap());
        assert!(has("20261222T100000"));
        assert!(!has("20261215T100000"), "removed by EXDATE");
        assert!(!has("20261223T100000"), "not on the rule");
        assert!(!well_formed("TTT"));
        assert!(!well_formed("20261301"));
    }
}
