export const writingStrings: Record<Locale, WritingStrings> = { en, ru }

/** The app's language from `<html lang>`: Russian for `ru`, English otherwise and outside a
 * browser. */
export function currentLocale(lang?: string): Locale {
  const value =
    lang ?? (typeof document === 'undefined' ? 'en' : document.documentElement.lang || 'en')
  return value.toLowerCase().startsWith('ru') ? 'ru' : 'en'
}
